def h(value: str) -> str:
    return sha256(value.encode("utf-8")).hexdigest()


def fixture(root: Path, index: int=0):
    """Make tiny synthetic bytes whose *exact* script is B3d3b source-bound."""
    original, _ = make_fake_unreviewed_inventory(index,root)
    facts=fact_fixture(index)
    proposal,slot,observations,anchor,script_registry,seal,_=facts["item"]
    plan=build_signed_preview_plan(
        proposal,slot,observations,seal=seal,
        anchor_manifest_sha256=anchor,registry=script_registry,
        excluded_creator_and_publisher_ids=EXCLUDED,now=NOW,
    )
    if original["plan"]["scene_count"]!=plan["scene_count"]:
        raise AssertionError("Test fixture source-bound visual layout changed")
    report=dict(original["report"])
    report["script_manifest_sha256"]=plan["script_manifest_sha256"]
    report["full_original_narration_sha256"]=plan["full_spoken_narration_sha256"]
    report["original_scene_ids"]=[x["scene_id"] for x in plan["scene_plan"]]
    report["computed_example_evidence_sha256"]=build_executed_demo(
        plan,proposal,RECIPES[index]
    )["evidence_packet_sha256"]
    media={
        **original,"plan":plan,"proposal":proposal,"slot":slot,
        "observations":observations,"seal":seal,
        "external_script_anchor_sha256":anchor,
        "script_registry":script_registry,"report":report,
    }
    fact_inputs={
        "proposal":proposal,"slot":slot,"observations":observations,
        "script_seal":seal,
        "external_script_anchor_sha256":anchor,
        "script_registry":script_registry,
        "proposed_atomic_claims":facts["claims_raw"],
        "source_excerpt_records":facts["excerpts"],
        "signed_reviews":facts["signed_reviews"],
        "fact_reviewer_registry":facts["reviewers"],
        "excluded_creator_and_publisher_ids":EXCLUDED,
        "now":NOW,
    }
    meta=UnapprovedMetadata(
        title_unreviewed=proposal["title"],
        description_unreviewed=(
            "Synthetic private test plan. Actual factual, visual, music, "
            "voice, originality and owner review must occur on the exact final files."
        ),
        thumbnail_claim_unreviewed="This is an unapproved educational technical thumbnail.",
        source_link_index_sha256=h("invented_source_citation_index"),
        previous_release_index_sha256=h("invented_prior_youtube_releases"),
        license_evidence_index_sha256=h("invented_audio_image_voice_rights"),
    )
    return media,fact_inputs,meta


def make_receipts(docket,*, change=None):
    keys={}
    roots={}
    records=[]
    for i,role in enumerate(ROLES):
        key=Ed25519PrivateKey.generate()
        reviewer=f"fixture_reviewer_{i+1:02d}"
        key_id=f"fixture_review_key_{i+1:02d}"
        roots[reviewer]=TrustedMockEditorialReviewer(
            reviewer_id=reviewer,key_id=key_id,
            public_key_ed25519_b64=base64.b64encode(
                key.public_key().public_bytes(
                    encoding=serialization.Encoding.Raw,
                    format=serialization.PublicFormat.Raw,
                )
            ).decode(),
            allowed_roles=(role,),
        )
        keys[role]=key
        claim=MockEditorialReviewClaim(
            purpose=PURPOSE,
            channel_id=docket["channel_id"],
            episode_id=docket["episode_id"],
            inventory_sha256=docket["full_media_inventory_sha256"],
            editorial_docket_sha256=docket["editorial_docket_sha256"],
            role=role,
            role_evidence_sha256=docket["required_role_evidence_sha256"][role],
            decision="MOCK_ACCEPT",
            reviewer_id=reviewer,
            key_id=key_id,
            reviewed_at_utc=(NOW-timedelta(minutes=5)).isoformat(),
            expires_at_utc=(NOW+timedelta(hours=4)).isoformat(),
            receipt_id=f"fixture_review_receipt_{i+1:02d}",
            review_notes=(
                "Only a disposable synthetic signature validating the structure "
                "of a future independently observed human editorial receipt."
            ),
            claimed_full_watch_seconds=(
                500 if role=="human_full_watch_listen" else 0
            ),
            synthetic_disclosure_choice=(
                "DISCLOSE_YES" if role=="altered_synthetic_disclosure"
                else "NOT_DECIDED"
            ),
        )
        if change and role==change[0]:
            claim=replace(claim,**change[1])
        records.append(
            DetachedMockEditorialReview(
                claim=claim,
                signature_ed25519_b64=base64.b64encode(
                    key.sign(DOMAIN+canonical(asdict(claim)))
                ).decode(),
            )
        )
    return keys,roots,records


def resign(record,key,**fields):
    claim=replace(record.claim,**fields)
    return DetachedMockEditorialReview(
        claim=claim,signature_ed25519_b64=base64.b64encode(
            key.sign(DOMAIN+canonical(asdict(claim)))
        ).decode(),
    )


class MockFinalEditorialEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.temp=TemporaryDirectory(prefix="flowminute-mock-final-review-")
        self.addCleanup(self.temp.cleanup)
        self.media,self.facts,self.metadata=fixture(Path(self.temp.name))
        self.docket=make_unapproved_editorial_docket(
            media_inputs=self.media,
            fact_review_inputs=self.facts,
            metadata=self.metadata,
        )
        self.keys,self.roots,self.reviews=make_receipts(self.docket)

    def verify(self,**changes):
        args=dict(
            docket=self.docket,
            media_inputs=self.media,
            fact_review_inputs=self.facts,
            metadata=self.metadata,
            records=self.reviews,
            registry=self.roots,
            excluded_creator_agent_and_publisher_ids=EXCLUDED,
            expected_externally_pinned_docket_sha256=self.docket["editorial_docket_sha256"],
            now=NOW,
        )
        args.update(changes)
        return verify_mock_final_editorial_receipts(**args)

    def test_seven_roles_are_cryptographically_distinct_but_humans_not_enrolled(self):
        result=self.verify()
        self.assertEqual(result["status"],STATUS_COMPLETE)
        self.assertEqual(result["mock_structurally_valid_receipt_count"],7)
        self.assertEqual(len(result["mock_role_coverage"]),7)
        self.assertEqual(self.docket["atomic_claim_count"],1)
        self.assertEqual(len(self.docket["required_role_evidence_sha256"]),7)
        self.assertTrue(result["all_mock_editorial_signature_shapes_valid"])
        for k in (
            "real_source_fact_accuracy_and_claim_completeness_verified",
            "real_human_full_watch_and_listen_verified",
            "live_voice_music_image_license_verified",
            "material_originality_against_real_channel_verified",
            "real_ai_disclosure_decision_verified",
            "owner_permission_and_signer_enrollment_authenticated",
            "private_immutable_review_ledger_connected",
            "real_provider_model_used",
            "youtube_upload_enabled",
            "youtube_schedule_enabled",
            "release_authorized",
        ):
            self.assertIs(result[k],False,k)

    def test_no_mock_review_can_rewrite_all_factual_or_owner_truth_flags(self):
        for k in (
            "editorial_real_humans_authenticated",
            "semantic_fact_truth_approved",
            "real_rights_or_voice_license_approved",
            "human_full_watch_observed_by_software",
            "repetitious_content_originality_approved",
            "owner_approved_synthetic_disclosure",
            "youtube_upload_enabled",
            "release_authorized",
        ):
            new=deepcopy(self.docket)
            new[k]=True
            with self.subTest(field=k),self.assertRaises(FinalEditorialEvidenceError):
                self.verify(docket=new)

    def test_all_shortcuts_missing_some_role_block_and_not_count_as_approval(self):
        for i in range(len(ROLES)):
            with self.subTest(role=ROLES[i]):
                rec=self.reviews[:i]+self.reviews[i+1:]
                response=self.verify(records=rec)
                self.assertEqual(response["status"],STATUS_BLOCKED)
                self.assertIn("missing_"+ROLES[i],response["mock_unresolved_roles_or_gaps"])
                self.assertFalse(response["release_authorized"])

    def test_signed_rejected_or_unresolved_role_blocks_all(self):
        for decision in ("MOCK_REJECT","MOCK_UNRESOLVED"):
            for role in ("voice_music_image_rights","human_full_watch_listen"):
                i=ROLES.index(role)
                records=list(self.reviews)
                records[i]=resign(records[i],self.keys[role],decision=decision)
                result=self.verify(records=records)
                self.assertEqual(result["status"],STATUS_BLOCKED)
                self.assertIn(role,result["mock_unresolved_roles_or_gaps"])
                self.assertFalse(result["youtube_upload_enabled"])

    def test_original_signed_inventory_cannot_pass_after_mp4_or_thumb_tamper(self):
        for name in ("UNAPPROVED_FULL_EDUCATION_TEST.mp4",
                     "UNAPPROVED_THUMBNAIL_TEST.png"):
            path=self.media["episode_folder"]/name
            original=path.read_bytes()
            path.write_bytes(original+b"mutated")
            with self.subTest(name=name), self.assertRaises(FinalEditorialEvidenceError):
                self.verify()
            path.write_bytes(original)

    def test_scene_or_srt_tampering_cannot_be_approved(self):
        for name in ("scene_01.png","scene_captions.srt"):
            path=self.media["episode_folder"]/name
            original=path.read_bytes()
            path.write_bytes(original+b"FAKE")
            with self.subTest(file=name),self.assertRaises(FinalEditorialEvidenceError):
                self.verify()
            path.write_bytes(original)

    def test_title_description_thumbnail_claim_replaced_requires_all_new_reviewer_signatures(self):
        for field,value in (
            ("title_unreviewed","A brand new misleading title"),
            ("description_unreviewed","A replacement description about a different fact claim."),
            ("thumbnail_claim_unreviewed","Profits magically grew by one thousand percent"),
            ("actual_synthetic_disclosure_decision","DISCLOSE_NO"),
        ):
            changed=replace(self.metadata,**{field:value})
            with self.subTest(field=field),self.assertRaises(FinalEditorialEvidenceError):
                self.verify(metadata=changed)

    def test_source_rights_and_prior_channel_roots_change_cannot_reuse_approval(self):
        for field in (
            "source_link_index_sha256",
            "previous_release_index_sha256",
            "license_evidence_index_sha256",
        ):
            with self.subTest(field=field):
                changed=replace(self.metadata,**{field:h("attacker swapped "+field)})
                with self.assertRaises(FinalEditorialEvidenceError):
                    self.verify(metadata=changed)

    def test_exact_signed_atomic_fact_docket_coverage_rechecked_and_needed(self):
        receipt=verify_independent_fact_records(**self.facts)
        self.assertEqual(receipt["expected_atomic_claim_count"],1)
        changed={**self.facts,"signed_reviews":self.facts["signed_reviews"][:-1]}
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(fact_review_inputs=changed)

    def test_no_claim_long_or_evening_short_is_not_vacuously_reviewed(self):
        for index in (1,2):
            with TemporaryDirectory(prefix="flowminute-claim-required-") as tmp:
                media,facts,meta=fixture(Path(tmp),index)
                receipt=verify_independent_fact_records(**facts)
                self.assertEqual(receipt["expected_atomic_claim_count"],0)
                with self.assertRaises(FinalEditorialEvidenceError):
                    make_unapproved_editorial_docket(
                        media_inputs=media,
                        fact_review_inputs=facts,
                        metadata=meta,
                    )

    def test_signed_replay_to_other_video_or_docket_denied(self):
        for field in ("episode_id","inventory_sha256","editorial_docket_sha256",
                      "role_evidence_sha256"):
            i=0
            record=self.reviews[i]
            new=replace(record.claim,**{field:"f"*64 if field!="episode_id" else "fm_20261106_long"})
            with self.subTest(field=field):
                records=list(self.reviews)
                records[i]=DetachedMockEditorialReview(
                    new,base64.b64encode(self.keys[ROLES[i]].sign(
                        DOMAIN+canonical(asdict(new))
                    )).decode(),
                )
                with self.assertRaises(FinalEditorialEvidenceError):
                    self.verify(records=records)

    def test_wrong_signer_key_forged_signature_or_reassigned_identity_denied(self):
        first=self.reviews[0]
        records=list(self.reviews)
        records[0]=DetachedMockEditorialReview(
            first.claim,self.reviews[1].signature_ed25519_b64
        )
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=records)
        roots=dict(self.roots)
        roots[first.claim.reviewer_id]=replace(
            roots[first.claim.reviewer_id],active=False
        )
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(registry=roots)
        recs=list(self.reviews)
        recs[1]=resign(
            recs[1],self.keys[ROLES[1]],
            reviewer_id=recs[0].claim.reviewer_id,
        )
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=recs)

    def test_same_public_key_shared_under_alternate_reviewer_id_denied(self):
        recs=list(self.reviews)
        roots=dict(self.roots)
        target=recs[1]
        shared=recs[0]
        roots[target.claim.reviewer_id]=replace(
            roots[target.claim.reviewer_id],
            public_key_ed25519_b64=roots[shared.claim.reviewer_id].public_key_ed25519_b64
        )
        recs[1]=resign(target,self.keys[ROLES[0]])
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=recs,registry=roots)

    def test_model_creator_or_uploader_cannot_sign_final_content_review(self):
        blocked=next(iter(EXCLUDED))
        rec=list(self.reviews)
        rec[0]=resign(rec[0],self.keys[ROLES[0]],reviewer_id=blocked)
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=rec)

    def test_signature_domain_separation_rejects_generic_ed25519_signing(self):
        rec=list(self.reviews)
        c=rec[0].claim
        rec[0]=DetachedMockEditorialReview(
            claim=c,signature_ed25519_b64=base64.b64encode(
                self.keys[ROLES[0]].sign(canonical(asdict(c)))
            ).decode(),
        )
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=rec)

    def test_docket_external_pin_cannot_be_computed_from_substituted_packet(self):
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(expected_externally_pinned_docket_sha256="a"*64)
        altered=deepcopy(self.docket)
        altered["required_role_evidence_sha256"][ROLES[0]]="b"*64
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(docket=altered)

    def test_no_future_stale_expired_or_naive_review_time(self):
        cases=(
            ((NOW+timedelta(minutes=1)).isoformat(),(NOW+timedelta(hours=2)).isoformat()),
            ((NOW-timedelta(hours=26)).isoformat(),(NOW+timedelta(hours=2)).isoformat()),
            ((NOW-timedelta(minutes=2)).isoformat(),(NOW-timedelta(seconds=1)).isoformat()),
            ("2026-11-04T15:00:00","2026-11-05T15:00:00"),
        )
        for reviewed,expires in cases:
            rec=list(self.reviews)
            rec[0]=resign(rec[0],self.keys[ROLES[0]],
                          reviewed_at_utc=reviewed,expires_at_utc=expires)
            with self.subTest(reviewed=reviewed),self.assertRaises(FinalEditorialEvidenceError):
                self.verify(records=rec)

    def test_full_watch_receipt_without_runtime_length_is_structurally_rejected(self):
        role="human_full_watch_listen"
        i=ROLES.index(role)
        rec=list(self.reviews)
        rec[i]=resign(rec[i],self.keys[role],claimed_full_watch_seconds=0)
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=rec)

    def test_disclosure_decision_missing_or_repurposed_denied(self):
        role="altered_synthetic_disclosure"
        i=ROLES.index(role)
        for option in ("NOT_DECIDED","AUTO_ASSUME_NO","MOCK_UNRESOLVED"):
            rec=list(self.reviews)
            rec[i]=resign(rec[i],self.keys[role],synthetic_disclosure_choice=option)
            if option=="MOCK_UNRESOLVED":
                self.assertEqual(self.verify(records=rec)["status"],STATUS_BLOCKED)
            else:
                with self.assertRaises(FinalEditorialEvidenceError):
                    self.verify(records=rec)
        rec=list(self.reviews)
        rec[0]=resign(rec[0],self.keys[ROLES[0]],
                      synthetic_disclosure_choice="DISCLOSE_YES")
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(records=rec)

    def test_duplicate_role_or_receipt_replay_denied(self):
        for position in (0,1):
            rec=list(self.reviews)
            rec[1]=rec[position]
            with self.assertRaises(FinalEditorialEvidenceError):
                self.verify(records=rec)

    def test_untrusted_fact_dossier_cannot_be_self_replaced(self):
        args=dict(self.facts)
        args["excluded_creator_and_publisher_ids"]=frozenset()
        with self.assertRaises(FinalEditorialEvidenceError):
            self.verify(fact_review_inputs=args)

    def test_no_actual_owner_signer_or_media_vault_claimed(self):
        out=self.verify()
        self.assertFalse(out["owner_permission_and_signer_enrollment_authenticated"])
        self.assertFalse(out["private_immutable_review_ledger_connected"])
        self.assertIsNone(out["actual_uploaded_youtube_video_id"])
        self.assertFalse(out["release_authorized"])


