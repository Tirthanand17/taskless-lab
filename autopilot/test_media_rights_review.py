"""Phase 3B: synthetic local 1080p portrait MP4/WAV and hashed evidence.

'INSPECTED_AWAITING_INDEPENDENT_REVIEW' is NOT a release, licensing,
naturalness, subtitle, content, or human reviewer approval.
"""
from __future__ import annotations
from dataclasses import replace
from datetime import datetime,timezone,timedelta
from hashlib import sha256
from pathlib import Path
import subprocess
import tempfile
import unittest

from autopilot.media_rights_review import (
    inspect_release_materials, RightsDeclaration
)
from autopilot.phase2_pipeline import digest
from autopilot.test_phase2_pipeline import fixtures
from autopilot.test_phase3_production import plan_data

NOW=datetime(2026,10,17,14,tzinfo=timezone.utc)


def filehash(path:Path)->str:
    return sha256(path.read_bytes()).hexdigest()


class IndependentMediaRightsPacketTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory=tempfile.TemporaryDirectory()
        root=Path(cls.directory.name)
        cls.video=root/"synthetic_blue_demo.mp4"
        cls.audio=root/"synthetic_tone_not_human.wav"
        cls.voice_license=root/"voice_rights_claim_example.txt"
        cls.screen_license=root/"screen_capture_rights_claim_example.txt"
        cls.voice_license.write_text(
            "TEST CLAIM ONLY: this synthetic test audio was generated by FFmpeg; "
            "no real voice provider permissions are established.",
            encoding="utf-8")
        cls.screen_license.write_text(
            "TEST CLAIM ONLY: the synthetic color-only image is produced by FFmpeg. "
            "No third party screen was recorded.",encoding="utf-8")
        jobs=(
            ["ffmpeg","-hide_banner","-loglevel","error","-y","-threads","2",
             "-f","lavfi","-i","color=c=blue:size=1080x1920:rate=20:d=3",
             "-f","lavfi","-i","sine=frequency=440:duration=3",
             "-map","0:v:0","-map","1:a:0","-c:v","libx264",
             "-preset","ultrafast","-crf","39","-pix_fmt","yuv420p",
             "-c:a","aac","-t","3",str(cls.video)],
            ["ffmpeg","-hide_banner","-loglevel","error","-y",
             "-f","lavfi","-i","sine=frequency=440:duration=3",
             "-c:a","pcm_s16le",str(cls.audio)]
        )
        for cmd in jobs:
            result=subprocess.run(cmd,text=True,capture_output=True,timeout=30)
            if result.returncode:
                raise RuntimeError("FFmpeg synthetic fixture preparation failed")

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def setUp(self):
        research,review,script,hooks,en,hi,lang_review=fixtures()
        board,voice,narration,subtitles,recipe=plan_data()
        sc0,sc1=board.scenes
        board=replace(board,scenes=(
            replace(sc0,end_ms=1500),
            replace(sc1,start_ms=1500,end_ms=3000)))
        voice=replace(voice,rights_reference=filehash(self.voice_license))
        narration=replace(narration,voice_plan_digest=digest(voice),
                          audio_sha256=filehash(self.audio),duration_ms=3000)
        subtitles=replace(subtitles,narration_digest=digest(narration),
                          cues=(replace(subtitles.cues[0],end_ms=1500),
                                replace(subtitles.cues[1],start_ms=1500,end_ms=3000)))
        recipe=replace(recipe,storyboard_digest=digest(board),
                       narration_digest=digest(narration),
                       subtitle_digest=digest(subtitles))
        voice_rights=RightsDeclaration(
            "asset_original_voice","voice",
            "Synthetic FFmpeg tone fixture test rights declaration only",
            str(self.voice_license),filehash(self.voice_license),
            True,True,True)
        screen_rights=RightsDeclaration(
            "asset_screen_capture_01","screen_capture",
            "Synthetic generated background test source description only",
            str(self.screen_license),filehash(self.screen_license),
            True,True,True)
        self.args=dict(video_path=self.video,narration_path=self.audio,
                       script=script,hooks=hooks,
                       language_review=lang_review,localized=hi,
                       expected_kind="short",expected_language="hi",
                       storyboard=board,voice=voice,narration=narration,
                       subtitles=subtitles,recipe=recipe,
                       rights=(voice_rights,screen_rights),now=NOW)

    def inspect(self,**overrides):
        return inspect_release_materials(**{**self.args,**overrides})

    def test_actual_video_audio_and_claim_documents_match_but_no_approval(self):
        out=self.inspect()
        self.assertEqual(out.status,"INSPECTED_AWAITING_INDEPENDENT_REVIEW")
        self.assertEqual(out.problems,())
        self.assertTrue(out.media_hash_verified)
        self.assertTrue(out.narration_hash_verified)
        self.assertTrue(out.rights_documents_hash_verified)
        self.assertTrue(out.voice_rights_record_matched)
        self.assertEqual(out.video.width,1080)
        self.assertEqual(out.video.height,1920)
        self.assertFalse(out.license_legality_verified)
        self.assertFalse(out.human_qa_completed)
        self.assertFalse(out.production_claims_authenticated)
        self.assertFalse(out.publishing_authorized)

    def test_missing_video_blocks_without_secret_or_upload(self):
        out=self.inspect(video_path=self.video.parent/"no_file.mp4")
        self.assertEqual(out.status,"BLOCKED_TECHNICAL_PREFLIGHT")
        self.assertIn("VIDEO_TECHNICAL_CHECK_FAILED",out.problems)

    def test_wrong_video_orientation_blocks(self):
        board=self.args["storyboard"]
        recipe=replace(self.args["recipe"],target_width=1920,target_height=1080)
        out=self.inspect(recipe=recipe)
        self.assertIn("STALE_OR_INVALID_PRODUCTION_PLAN",out.problems)

    def test_audio_hash_claim_does_not_substitute_for_actual_file(self):
        narration=replace(self.args["narration"],audio_sha256="c"*64)
        subtitles=replace(self.args["subtitles"],narration_digest=digest(narration))
        recipe=replace(self.args["recipe"],narration_digest=digest(narration),
                       subtitle_digest=digest(subtitles))
        out=self.inspect(narration=narration,subtitles=subtitles,recipe=recipe)
        self.assertIn("NARRATION_FILE_HASH_MISMATCH",out.problems)
        self.assertFalse(out.narration_hash_verified)

    def test_missing_audio_blocks(self):
        out=self.inspect(narration_path=self.audio.parent/"missing_voice.wav")
        self.assertIn("AUDIO_TECHNICAL_CHECK_FAILED",out.problems)

    def test_changed_rights_document_rejected_by_sha(self):
        x=self.args["rights"][1]
        wrong=replace(x,license_document_sha256="1"*64)
        out=self.inspect(rights=(self.args["rights"][0],wrong))
        self.assertIn("LICENSE_EVIDENCE_FILE_MISSING_OR_CHANGED",out.problems)
        self.assertFalse(out.rights_documents_hash_verified)

    def test_missing_storyboard_asset_license_blocks(self):
        out=self.inspect(rights=self.args["rights"][:1])
        self.assertIn("STORYBOARD_ASSET_WITHOUT_RIGHTS_DECLARATION",out.problems)

    def test_missing_voice_license_blocks(self):
        out=self.inspect(rights=self.args["rights"][1:])
        self.assertIn("VOICE_RIGHTS_DECLARATION_MISSING_OR_AMBIGUOUS",out.problems)

    def test_wrong_voice_license_digest_blocks(self):
        voice=replace(self.args["voice"],rights_reference="f"*64)
        narration=replace(self.args["narration"],voice_plan_digest=digest(voice))
        subtitles=replace(self.args["subtitles"],narration_digest=digest(narration))
        recipe=replace(self.args["recipe"],narration_digest=digest(narration),
                       subtitle_digest=digest(subtitles))
        out=self.inspect(voice=voice,narration=narration,subtitles=subtitles,recipe=recipe)
        self.assertIn("VOICE_RIGHTS_REFERENCE_MISMATCH",out.problems)

    def test_commercial_rights_not_claimed_blocks(self):
        record=replace(self.args["rights"][1],commercial_use_claimed=False)
        out=self.inspect(rights=(self.args["rights"][0],record))
        self.assertIn("NO_DECLARED_COMMERCIAL_ADAPTATION_RIGHTS",out.problems)

    def test_expired_license_document_blocks(self):
        record=replace(self.args["rights"][1],
                       expires_at_utc=(NOW-timedelta(seconds=1)).isoformat())
        out=self.inspect(rights=(self.args["rights"][0],record))
        self.assertIn("EXPIRED_OR_UNVERIFIED_LICENSE_DATE",out.problems)

    def test_future_expiry_can_only_pass_document_presence(self):
        record=replace(self.args["rights"][1],
                       expires_at_utc=(NOW+timedelta(days=1)).isoformat())
        out=self.inspect(rights=(self.args["rights"][0],record))
        self.assertTrue(out.rights_documents_hash_verified)
        self.assertFalse(out.license_legality_verified)

    def test_stale_render_recipe_stops_before_file_check(self):
        recipe=replace(self.args["recipe"],subtitle_digest="1"*64)
        out=self.inspect(recipe=recipe)
        self.assertEqual(out.status,"BLOCKED_TECHNICAL_PREFLIGHT")
        self.assertEqual(out.video.status,"NOT_INSPECTED")

    def test_language_mismatch_fails_closed(self):
        out=self.inspect(expected_language="en")
        self.assertIn("STALE_OR_INVALID_PRODUCTION_PLAN",out.problems)

    def test_missing_rights_all_blocks(self):
        out=self.inspect(rights=())
        self.assertIn("INVALID_RIGHTS_MANIFEST_SIZE",out.problems)

    def test_duplicate_rights_records_block(self):
        out=self.inspect(rights=(self.args["rights"][0],self.args["rights"][0],
                                 self.args["rights"][1]))
        self.assertIn("DUPLICATE_OR_INVALID_RIGHTS_DECLARATION",out.problems)

    def test_document_is_not_voice_rights_proof(self):
        out=self.inspect()
        self.assertFalse(out.license_legality_verified)
        self.assertFalse(out.publishing_authorized)
        self.assertNotIn("approved",out.status.lower())

if __name__=="__main__":
    unittest.main()
