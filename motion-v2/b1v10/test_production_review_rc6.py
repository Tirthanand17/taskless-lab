"""RC6 review adapter: offline adversarial tests, no publisher invocation."""
import copy,hashlib,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
import production_review_rc6 as q
from autopilot.branch1_recovery import RecoveryRefused
class ProductionReviewTests(unittest.TestCase):
 def reports(self,k):
  return [q.read(n) for n in q.CATALOG[k][:3]]
 def test_catalog_and_legacy_gate(self):
  for k,first in [("sha256",156),("float",102),("git",537)]:
   c,r,n=self.reports(k)
   self.assertEqual(q.verify_catalog(k,c,r,n),first)
   policy=q.legacy_policy(k,n,first)
   self.assertFalse(policy["creative_pass"])
   self.assertFalse(policy["proof_within_two_seconds"])
   self.assertFalse(policy["first_real_action_by_three_seconds"])
 def test_reject_spoofed_approval(self):
  for k in q.CATALOG:
   c,r,n=self.reports(k)
   for target,field in [(c,"release_authorized"),(r,"release_authorized"),(c,"legacy_xvfb_receipt_compatible")]:
    target[field]=True
    with self.assertRaises(RecoveryRefused):q.verify_catalog(k,c,r,n)
    target[field]=False
 def test_reject_wrong_method_and_link(self):
  c,r,n=self.reports("float")
  c["method"]="xvfb_xterm_ffmpeg_live"
  with self.assertRaises(RecoveryRefused):q.verify_catalog("float",c,r,n)
  c,r,n=self.reports("float");r["capture_sha256"]="a"*64
  with self.assertRaises(RecoveryRefused):q.verify_catalog("float",c,r,n)
 def test_reject_invalid_clock_and_crop(self):
  for field,value in [("frames",1),("audio_samples",1),("resolution",[720,1280]),("observed_crops",[])]:
   c,r,n=self.reports("sha256");r[field]=value
   with self.assertRaises(RecoveryRefused):q.verify_catalog("sha256",c,r,n)
 def test_hash_mismatch(self):
  with tempfile.TemporaryDirectory() as d:
   p=Path(d)/"capture.mp4";p.write_bytes(b"original")
   digest=hashlib.sha256(b"original").hexdigest();q.exact(p,digest)
   p.write_bytes(b"tampered")
   with self.assertRaises(RecoveryRefused):q.exact(p,digest)
 def test_symlink_rejection(self):
  with tempfile.TemporaryDirectory() as d:
   p=Path(d)/"file.mp4";p.write_bytes(b"fixture")
   with patch.object(Path,"is_symlink",return_value=True):
    with self.assertRaises(RecoveryRefused):q.file_ok(p)
 def test_final_gate_never_issues_approval(self):
  for k in q.CATALOG:
   c,r,n=self.reports(k)
   # Actual decode evidence is separately generated by the CLI on real files.
   with patch.object(q,"exact"),patch.object(q,"inspect_video",side_effect=[c.get("decoded_frames",c.get("frames")),r["frames"]]),patch.object(q,"inspect_audio",return_value={"decoded_samples":r["audio_samples"]}):
    out=q.verify(k,Path("fixture"),Path("fixture"),"ffmpeg")
   self.assertTrue(out["technical_review_pass"])
   self.assertTrue(out["publisher_unsigned_rejected"])
   self.assertFalse(out["owner_approval"])
   self.assertFalse(out["release_authorized"])
if __name__=="__main__":unittest.main()
