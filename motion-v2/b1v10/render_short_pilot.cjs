const path=require('path'); const fs=require('fs');
const {bundle}=require('@remotion/bundler');
const {selectComposition,renderMedia}=require('@remotion/renderer');
(async()=>{const out=path.resolve(process.argv[2]);fs.mkdirSync(out,{recursive:true});
const url=await bundle({entryPoint:path.join(__dirname,'short-pilot.tsx'),onProgress:()=>{}});
const composition=await selectComposition({serveUrl:url,id:'B1v10Sha256Short',logLevel:'error'});
let last=0;
await renderMedia({serveUrl:url,composition,codec:'h264',crf:18,pixelFormat:'yuv420p',concurrency:2,outputLocation:path.join(out,'silent.mp4'),logLevel:'error',overwrite:true,onProgress:({renderedFrames})=>{if(renderedFrames-last>=90){last=renderedFrames;console.log('Rendered',renderedFrames,'/',composition.durationInFrames);}}});
console.log('RENDER COMPLETE',composition.durationInFrames);
})().catch(e=>{console.error(e);process.exitCode=1});
